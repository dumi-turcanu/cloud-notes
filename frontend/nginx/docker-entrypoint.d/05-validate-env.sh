#!/bin/sh
# Validates API_UPSTREAM / API_UPSTREAM_HOST and writes the (already validated)
# values into an nginx include. Runs before the base image's template step.
# Writing a file instead of exporting variables keeps untrusted characters out
# of the nginx configuration: the values are checked against strict patterns.
set -eu

fail() {
    echo "ERROR: $*" >&2
    exit 1
}

upstream="${API_UPSTREAM:-}"
[ -n "$upstream" ] || fail "API_UPSTREAM is required, e.g. http://backend:8080 or https://api.example.com"

# scheme://host[:port] — no path, query, credentials or whitespace.
host_re='(\[[0-9A-Fa-f:]+\]|[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?)(:[0-9]{1,5})?'
printf '%s\n' "$upstream" | grep -Eq "^https?://${host_re}\$" ||
    fail "API_UPSTREAM='${upstream}' is malformed; expected scheme://host[:port] without a path"

upstream_host="${API_UPSTREAM_HOST:-${upstream#*://}}"
printf '%s\n' "$upstream_host" | grep -Eq "^${host_re}\$" ||
    fail "API_UPSTREAM_HOST='${upstream_host}' is malformed; expected host[:port]"

# The map key is a constant, so each variable always yields the configured value.
cat > /etc/nginx/conf.d/00-upstream.conf <<CONF
# Generated by 05-validate-env.sh at container start. Do not edit.
map \$server_name \$api_upstream      { default "${upstream}"; }
map \$server_name \$api_upstream_host { default "${upstream_host}"; }
CONF
echo "05-validate-env.sh: proxying /api/ to ${upstream} (Host: ${upstream_host})"
